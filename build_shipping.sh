#!/usr/bin/env bash
# HESPERIA — One script to build shipped artifacts. Uses only sealed entry points.
# Copyright © 2026 igareosh.com. See LEGAL_NOTICE.md.
#
# Usage: ./build_shipping.sh [cli|api|all]
# Sequence: import-boundary → sealing scan → (consistency) → build CLI → build API → checksums → manifest
#
# Hard-fail (build stops) on:
#   - import-boundary check failure
#   - sealing scan forbidden strings in public tree
#   - (optional) projection/release content policy failure

set -e
REPO="$(cd "$(dirname "$0")" && pwd)"
cd "$REPO"
RELEASE="$REPO/release"
DIST="$REPO/dist"
if [ -z "${HESPERIA_VERSION}" ]; then
  echo "[FATAL] HESPERIA_VERSION is not set"
  exit 1
fi
VERSION="${HESPERIA_VERSION}"
GIT_COMMIT="$(git rev-parse HEAD 2>/dev/null || echo "nogit")"
BUILD_TS="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

# Always embed the requested release version into the shipping version_info.
# This keeps API/CLI builds consistent and prevents environment-dependent downgrades.
VERSION_FILE="$REPO/runtime/shipping/version_info.py"
cat > "$VERSION_FILE" << EOF
# Generated by build_shipping.sh — do not edit manually.
VERSION = "$VERSION"
COMMIT = "$GIT_COMMIT"
BUILD = "$BUILD_TS"
EOF

run_checks() {
  echo "=== 1. Import boundary check ==="
  if ! python3 tools/check_import_boundary.py; then
    echo "Import boundary check failed. Build stopped." >&2
    exit 1
  fi
  echo "=== 2. Sealing scan (forbidden terms in public tree) ==="
  if [[ -f tools/sealing_scan.py ]]; then
    if ! python3 tools/sealing_scan.py; then
      echo "Sealing scan failed. Build stopped." >&2
      exit 1
    fi
  fi
  echo "=== 3. Consistency checks (optional; run pytest or A1–A5 if needed) ==="
  # Optional: python3 -m pytest tests/ -k "consistency or projection" --tb=short -q || exit 1
  true
}

build_cli() {
  echo "=== Build CLI (Nuitka standalone + onefile) ==="
  if ! command -v nuitka3 &>/dev/null; then
    echo "nuitka3 not found. Skip CLI build or: pip install nuitka" >&2
    return 1
  fi
  ./tools/build_nuitka_cli.sh
}

build_api() {
  echo "=== Build API Docker image ==="
  if ! command -v docker &>/dev/null; then
    echo "docker not found. Skip API build." >&2
    return 1
  fi
  cp -f .dockerignore.shipping .dockerignore 2>/dev/null || true
  docker build -f Dockerfile.shipping -t hesperia-api:latest .
  mkdir -p "$RELEASE"
  docker save hesperia-api:latest -o "$RELEASE/hesperia-api-image.tar"
  echo "Image saved to $RELEASE/hesperia-api-image.tar"
}

write_manifest() {
  echo "=== Generate release/manifest.json ==="
  mkdir -p "$RELEASE"
  MANIFEST="$RELEASE/manifest.json"
  CHECKSUMS="$RELEASE/checksums.txt"
  : > "$CHECKSUMS"

  if [[ -f "$DIST/hesperia-cli.bin" ]]; then
    (cd "$DIST" && sha256sum hesperia-cli.bin 2>/dev/null >> "$CHECKSUMS" || true)
  fi
  if [[ -f "$RELEASE/hesperia-api-image.tar" ]]; then
    (cd "$RELEASE" && sha256sum hesperia-api-image.tar >> "$CHECKSUMS" || true)
  fi

  SCHEMA_SHA=""
  if [[ -f "$REPO/assets/public/public_output_schema.json" ]]; then
    SCHEMA_SHA="$(sha256sum < "$REPO/assets/public/public_output_schema.json" | cut -d' ' -f1)"
    echo "$SCHEMA_SHA" > "$RELEASE/schema_sha256.txt"
    echo "Schema SHA256: $SCHEMA_SHA (release/schema_sha256.txt; set HESPERIA_SCHEMA_SHA256 for runtime check)"
  fi

  cat > "$MANIFEST" << EOF
{
  "version": "$VERSION",
  "git_commit": "$GIT_COMMIT",
  "build_timestamp": "$BUILD_TS",
  "included_artifacts": [
    "dist/hesperia-cli/",
    "dist/hesperia-cli.bin",
    "release/hesperia-api-image.tar"
  ],
  "checksums_file": "release/checksums.txt",
  "entry_points": ["analyze", "compare", "batch-analyze", "serve", "health"]
}
EOF
  echo "Checksums in $CHECKSUMS"
  echo "Manifest written to $MANIFEST"
}

target="${1:-all}"
case "$target" in
  manifest)
    write_manifest
    ;;
  cli)
    run_checks
    build_cli
    write_manifest
    ;;
  api)
    run_checks
    build_api
    write_manifest
    ;;
  all)
    run_checks
    build_cli || true
    build_api || true
    write_manifest
    ;;
  *)
    echo "Usage: $0 [cli|api|all]" >&2
    exit 1
    ;;
esac
echo "Done: $target"
